public class Datatypes{

    public static void main(String[] args){

        System.out.println("Datatypes in Java:");
        byte bty = 10;
        int num = 13203;
        short shrt = 1000;
        long lng = 100000L;
        float flt = 10.34f;
        double dbl = 10.34234342384793473d;
        boolean tr = true;
        boolean fl = false;
        char chr = 'A';

        System.out.println("Byte: " + bty);
        System.out.println("Integer: " + num);
        System.out.println("Short: " + shrt);
        System.out.println("Long: " + lng);
        System.out.println("Float: " + flt);
        System.out.println("Double: " + dbl);
        System.out.println("Boolean (true): " + tr);
        System.out.println("Boolean (false): " + fl);
        System.out.println("Character: " + chr);

    }
}